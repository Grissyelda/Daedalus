#!/usr/bin/env python3
"""Generate GrizzTech4's prototype ("dev") textures and the engine test map.

Writes, under the given content folder:
  textures/dev/*.tga                 grid textures for blocking out levels
  textures/editor/floorgrid.tga      the editor's floor grid
  materials/dev.mtr                  materials for those textures
  maps/testmaps/gt4_test_room.map    a lit room with a player start

Usage:
  make_dev_content.py --out content

Needs Pillow (pip install pillow).
"""

import argparse
import os

from PIL import Image, ImageDraw

# name: (base colour, line colour, label)
DEV_TEXTURES = {
    "grid_floor":   ((118, 118, 122), (88, 88, 94)),
    "grid_wall":    ((156, 146, 136), (120, 110, 100)),
    "grid_ceiling": ((84, 88, 98), (64, 66, 74)),
    "grid_accent":  ((214, 128, 56), (170, 92, 34)),
    "grid_trim":    ((70, 120, 160), (48, 88, 122)),
}

SIZE = 256          # texture size in pixels; one texture repeat = 128 map units
TEXTURE_UNITS = 128


def make_texture(path, base, line):
    img = Image.new("RGB", (SIZE, SIZE), base)
    draw = ImageDraw.Draw(img)
    minor = SIZE // 8     # 16 map units
    for i in range(0, SIZE, minor):
        draw.line([(i, 0), (i, SIZE)], fill=line, width=1)
        draw.line([(0, i), (SIZE, i)], fill=line, width=1)
    major = tuple(max(0, c - 24) for c in line)
    draw.rectangle([0, 0, SIZE - 1, SIZE - 1], outline=major, width=3)
    draw.line([(SIZE // 2, 0), (SIZE // 2, SIZE)], fill=major, width=2)
    draw.line([(0, SIZE // 2), (SIZE, SIZE // 2)], fill=major, width=2)
    img.save(path)


def make_floorgrid(path):
    """The editor's floor grid: transparent, with faint lines every grid step and a
    stronger line every 8 steps (one texture repeat)."""
    size = 256
    img = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    draw = ImageDraw.Draw(img)
    step = size // 8
    for i in range(0, size, step):
        draw.line([(i, 0), (i, size)], fill=(255, 255, 255, 70), width=1)
        draw.line([(0, i), (size, i)], fill=(255, 255, 255, 70), width=1)
    draw.line([(0, 0), (0, size)], fill=(255, 255, 255, 160), width=2)
    draw.line([(0, 0), (size, 0)], fill=(255, 255, 255, 160), width=2)
    img.save(path)


def write_materials(path):
    with open(path, "w", newline="\n") as f:
        f.write("/*\n\tGrizzTech4 prototype materials\n\n"
                "\tGrid textures for blocking out levels: the small squares are 16 units,\n"
                "\tthe large ones 64 units. Generated by scripts/content/make_dev_content.py.\n*/\n\n")
        for name in DEV_TEXTURES:
            f.write(f"textures/dev/{name}\n{{\n"
                    f"\tqer_editorimage\ttextures/dev/{name}.tga\n"
                    f"\tdiffusemap\t\ttextures/dev/{name}.tga\n"
                    f"\tbumpmap\t\t\t_flat\n"
                    f"}}\n\n")


# ---------------------------------------------------------------------------
# map writing
# ---------------------------------------------------------------------------

TEXMAT = f"( ( {1.0 / TEXTURE_UNITS:.7f} 0 0 ) ( 0 {1.0 / TEXTURE_UNITS:.7f} 0 ) )"


def box_brush(mins, maxs, material, top=None, sides=None, bottom=None):
    """An axis-aligned box as a brushDef3. Planes point outward: normal . p + d = 0."""
    top = top or material
    bottom = bottom or material
    sides = sides or material
    (x0, y0, z0), (x1, y1, z1) = mins, maxs
    faces = [
        ((0, 0, 1), -z1, top),
        ((0, 0, -1), z0, bottom),
        ((1, 0, 0), -x1, sides),
        ((-1, 0, 0), x0, sides),
        ((0, 1, 0), -y1, sides),
        ((0, -1, 0), y0, sides),
    ]
    lines = [" brushDef3\n {\n"]
    for (nx, ny, nz), d, mat in faces:
        lines.append(f"  ( {nx} {ny} {nz} {d} ) {TEXMAT} \"textures/dev/{mat}\" 0 0 0\n")
    lines.append(" }\n")
    return "".join(lines)


def write_test_map(path):
    room = 768
    height = 256
    wall = 16

    brushes = [
        # floor, ceiling and four walls
        box_brush((-wall, -wall, -wall), (room + wall, room + wall, 0), "grid_floor"),
        box_brush((-wall, -wall, height), (room + wall, room + wall, height + wall), "grid_ceiling"),
        box_brush((-wall, -wall, 0), (0, room + wall, height), "grid_wall"),
        box_brush((room, -wall, 0), (room + wall, room + wall, height), "grid_wall"),
        box_brush((0, -wall, 0), (room, 0, height), "grid_wall"),
        box_brush((0, room, 0), (room, room + wall, height), "grid_wall"),
        # a raised platform with a step, and a pillar, to give scale
        box_brush((448, 448, 0), (704, 704, 32), "grid_trim"),
        box_brush((416, 448, 0), (448, 704, 16), "grid_trim"),
        box_brush((256, 192, 0), (320, 256, 192), "grid_accent"),
    ]

    out = ["Version 3\n",
           "// entity 0\n{\n",
           "\"classname\" \"worldspawn\"\n",
           "\"def_player\" \"player\"\n"]
    for i, brush in enumerate(brushes):
        out.append(f"// primitive {i}\n{{\n{brush}}}\n")
    out.append("}\n")

    entities = [
        {"classname": "info_player_start", "name": "info_player_start_1",
         "origin": "96 384 1", "angle": "0"},
        {"classname": "light", "name": "light_main",
         "origin": "384 384 224", "light_radius": "520 520 300",
         "_color": "1 0.92 0.82"},
        {"classname": "light", "name": "light_platform",
         "origin": "640 640 160", "light_radius": "300 300 220",
         "_color": "0.55 0.7 1"},
        {"classname": "light", "name": "light_entry",
         "origin": "96 96 200", "light_radius": "320 320 260",
         "_color": "1 0.6 0.35"},
    ]
    for i, ent in enumerate(entities, start=1):
        out.append(f"// entity {i}\n{{\n")
        for k, v in ent.items():
            out.append(f"\"{k}\" \"{v}\"\n")
        out.append("}\n")

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write("".join(out))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    tex_dir = os.path.join(args.out, "textures", "dev")
    os.makedirs(tex_dir, exist_ok=True)
    for name, (base, line) in DEV_TEXTURES.items():
        make_texture(os.path.join(tex_dir, f"{name}.tga"), base, line)

    editor_dir = os.path.join(args.out, "textures", "editor")
    os.makedirs(editor_dir, exist_ok=True)
    make_floorgrid(os.path.join(editor_dir, "floorgrid.tga"))

    os.makedirs(os.path.join(args.out, "materials"), exist_ok=True)
    write_materials(os.path.join(args.out, "materials", "dev.mtr"))
    write_test_map(os.path.join(args.out, "maps", "testmaps", "gt4_test_room.map"))
    print("wrote dev textures, materials/dev.mtr and maps/testmaps/gt4_test_room.map")


if __name__ == "__main__":
    main()
